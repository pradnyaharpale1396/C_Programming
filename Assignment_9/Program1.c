//WAP to accept number from a user & display below pattern
//Input : 5
//Output : *  *  *   *   *   #   #   #   #   #
#include<stdio.h>
#include<stdlib.h>

///////////////////////////////////////////////////////////////////////////
//
//  Function Name   :   Display
//  Input           :   Integer
//  Output          :   Print * #
//  Description     :   Accept number and print the pattern * & # for accpeted number of time
//  Date            :   1/11/2026
//  Author          :   Pradnya Anil Harpale
//
///////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{ 
    int iCnt = 0;

    if(iNo < 0)
    {
        iNo = -iNo;
    }

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("*\t");   
    }
    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("#\t");   
    }


}

///////////////////////////////////////////////////////////////////////////
//
//  Entry point of the application
//
///////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number : ");
    scanf("%d", &iValue);

    Display(iValue);

    return EXIT_SUCCESS;
}

