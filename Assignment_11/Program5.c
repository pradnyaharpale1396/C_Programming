/*WAP which accepts range from user and display all numbers in between that range in reverse order

Input :  23      35
Output : 35      34      33      32      31      30      29      28      27      26      25      24      23
*/
#include<stdio.h>
#include<stdlib.h>

///////////////////////////////////////////////////////////////////////////
//
//  Function Name   :   RangeDisplayRev
//  Input           :   Integer, Integer
//  Output          :   Integer
//  Description     :   Display all numbers between the given range
//  Date            :   7/11/2026
//  Author          :   Pradnya Anil Harpale
//
///////////////////////////////////////////////////////////////////////////

void RangeDisplayRev(int iStart, int iEnd)
{ 
    int iCnt = 0;

    if(iStart > iEnd)
    {
        printf("Invalid range..");
    }

    for(int iCnt = iEnd; iCnt >= iStart; iCnt--)
    {
        printf("%d\t", iCnt);
    }
}

///////////////////////////////////////////////////////////////////////////
//
//  Entry point of the application
//
///////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue1 = 0, iValue2 = 0;

    printf("Enter starting point : ");
    scanf("%d", &iValue1);

    printf("Enter ending point : ");
    scanf("%d", &iValue2);

    RangeDisplayRev(iValue1, iValue2);

    return EXIT_SUCCESS;
}

